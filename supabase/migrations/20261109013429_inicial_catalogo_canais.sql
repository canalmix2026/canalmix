create table public.catalog_admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create table public.channels (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name text not null check (length(name) between 2 and 80),
  category_id smallint not null references public.categories (id) on delete restrict,
  embed_url text not null check (length(embed_url) <= 2048 and embed_url ~* '^https://'),
  thumbnail_url text check (
    thumbnail_url is null or
    (length(thumbnail_url) <= 2048 and thumbnail_url ~* '^https://')
  ),
  official_url text check (
    official_url is null or
    (length(official_url) <= 2048 and official_url ~* '^https://')
  ),
  is_published boolean not null default false,
  published_at timestamptz,
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index channels_published_category_name_idx
  on public.channels (category_id, lower(name))
  where is_published;
create index channels_created_at_idx on public.channels (created_at desc);

create function private.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = pg_catalog.now();
  return new;
end;
$$;

revoke all on function private.touch_updated_at() from public, anon, authenticated;

create trigger channels_touch_updated_at
before update on public.channels
for each row execute function private.touch_updated_at();

alter table public.categories enable row level security;
alter table public.catalog_admins enable row level security;
alter table public.channels enable row level security;

create policy "Anyone can read categories"
  on public.categories for select
  to anon, authenticated
  using (true);

create policy "An admin can read their own membership"
  on public.catalog_admins for select
  to authenticated
  using (user_id = (select auth.uid()));

create policy "Visitors can read published channels"
  on public.channels for select
  to anon, authenticated
  using (is_published);

create policy "Admins can read every channel"
  on public.channels for select
  to authenticated
  using (
    exists (
      select 1
      from public.catalog_admins
      where catalog_admins.user_id = (select auth.uid())
    )
  );

create policy "Admins can add channels"
  on public.channels for insert
  to authenticated
  with check (
    created_by = (select auth.uid())
    and exists (
      select 1
      from public.catalog_admins
      where catalog_admins.user_id = (select auth.uid())
    )
  );

create policy "Admins can update channels"
  on public.channels for update
  to authenticated
  using (
    exists (
      select 1
      from public.catalog_admins
      where catalog_admins.user_id = (select auth.uid())
    )
  )
  with check (
    exists (
      select 1
      from public.catalog_admins
      where catalog_admins.user_id = (select auth.uid())
    )
  );

create policy "Admins can delete channels"
  on public.channels for delete
  to authenticated
  using (
    exists (
      select 1
      from public.catalog_admins
      where catalog_admins.user_id = (select auth.uid())
    )
  );

revoke all on public.categories, public.catalog_admins, public.channels from public, anon, authenticated;
grant usage on schema public to anon, authenticated;
grant select on public.categories to anon, authenticated;
grant select on public.catalog_admins to authenticated;
grant select on public.channels to anon, authenticated;
grant insert, update, delete on public.channels to authenticated;
